"use client";
import { useEffect, useMemo } from "react";
import * as THREE from "three";
import { Sparkles } from "@react-three/drei";
import windowData from "@/data/windows.json";
import { SUN_DIRECTION } from "@/lib/sun";
import { useChurchStore } from "@/store/church-store";

/**
 * Coloured sunlight through the stained glass.
 *
 * Only windows that face the sun let light in. For each one the window rectangle is projected
 * along the sun direction onto the floor: a coloured patch of light on the floor, a faint beam
 * between glass and floor, and a few dust motes drifting in the beam. Window placement comes from
 * src/data/windows.json (generated by scripts/extract-windows.py).
 *
 * This is an approximation, not a real light projection: the patches are drawn on the floor only
 * (pews and walls are not tinted). The glass meshes cast shadows (see Church.tsx), so the sun does
 * not also spill through the windows as plain white light.
 */

type Colours = Record<string, number>;
interface AreaDef {
  name: string;
  centre: number[];
  radius: number;
}
interface WindowDef {
  area: number;
  centre: number[];
  right: number[];
  outward: number[];
  width: number;
  height: number;
  colours: Colours;
}

const PALETTE: Record<string, string> = {
  amber: "#ffb020",
  cobalt: "#2f5bff",
  emerald: "#1fc65e",
  ruby: "#ff2a3c",
  teal: "#16cbc2",
  violet: "#a043ff",
};
const FLOOR_Y = 0.03;
const MIN_SUN = 0.12; // windows facing away from the sun get no light
const HORIZONTAL_SUN = Math.hypot(SUN_DIRECTION.x, SUN_DIRECTION.z);

function rngFrom(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** A small mosaic of coloured panes separated by dark lead lines, in this window's colour mix. */
function makeMosaic(colours: Colours, seed: number): THREE.CanvasTexture {
  const cols = 4;
  const rows = 10;
  const cell = 16;
  const gutter = 2;
  const canvas = document.createElement("canvas");
  canvas.width = cols * cell;
  canvas.height = rows * cell;
  const ctx = canvas.getContext("2d")!;
  ctx.fillStyle = "#000";
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  const rand = rngFrom(seed);
  const entries = Object.entries(colours).filter(([, w]) => w > 0);
  const total = entries.reduce((s, [, w]) => s + w, 0);
  const pick = () => {
    let r = rand() * total;
    for (const [name, w] of entries) {
      r -= w;
      if (r <= 0) return PALETTE[name];
    }
    return PALETTE.amber;
  };
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      ctx.fillStyle = pick();
      ctx.fillRect(x * cell + gutter, y * cell + gutter, cell - gutter * 2, cell - gutter * 2);
    }
  }
  const tex = new THREE.CanvasTexture(canvas);
  tex.colorSpace = THREE.SRGBColorSpace;
  tex.minFilter = THREE.LinearFilter;
  tex.magFilter = THREE.LinearFilter;
  return tex;
}

interface Shaft {
  key: number;
  intensity: number;
  pool: THREE.BufferGeometry | null;
  beam: THREE.BufferGeometry;
  texture: THREE.CanvasTexture;
  beamColor: THREE.Color;
  mid: [number, number, number];
}

// Worship areas are regular hexagons with vertices at +-X: edge normals at 90, 30, -30, -90, -150, 150 deg.
const HEX_NORMALS: [number, number][] = [90, 30, -30, -90, -150, 150].map((deg) => [
  Math.cos(THREE.MathUtils.degToRad(deg)),
  Math.sin(THREE.MathUtils.degToRad(deg)),
]);
const HEX_APOTHEM = Math.cos(Math.PI / 6);
/** Rays start on the wall, so allow a little slack when testing whether they are still inside. */
const WALL_SLACK = 0.3;

interface PoolPoint {
  x: number;
  z: number;
  u: number;
  v: number;
}

/** Sutherland-Hodgman clip of the pool polygon against the hexagon, interpolating UVs. */
function clipToArea(poly: PoolPoint[], area: AreaDef): PoolPoint[] {
  const apothem = area.radius * HEX_APOTHEM;
  let out = poly;
  for (const [nx, nz] of HEX_NORMALS) {
    const dist = (p: PoolPoint) => nx * (p.x - area.centre[0]) + nz * (p.z - area.centre[1]) - apothem;
    const next: PoolPoint[] = [];
    for (let i = 0; i < out.length; i++) {
      const a = out[i];
      const b = out[(i + 1) % out.length];
      const da = dist(a);
      const db = dist(b);
      if (da <= 0) next.push(a);
      if (da <= 0 !== db <= 0) {
        const t = da / (da - db);
        next.push({ x: a.x + (b.x - a.x) * t, z: a.z + (b.z - a.z) * t, u: a.u + (b.u - a.u) * t, v: a.v + (b.v - a.v) * t });
      }
    }
    out = next;
    if (out.length === 0) break;
  }
  return out;
}

/** How far (0..1) along start->end the ray stays inside the hexagon. */
function exitParam(start: THREE.Vector3, end: THREE.Vector3, area: AreaDef): number {
  const bound = area.radius * HEX_APOTHEM + WALL_SLACK;
  let tMax = 1;
  for (const [nx, nz] of HEX_NORMALS) {
    const along = nx * (end.x - start.x) + nz * (end.z - start.z);
    if (along > 1e-6) {
      const at0 = nx * (start.x - area.centre[0]) + nz * (start.z - area.centre[1]);
      tMax = Math.min(tMax, (bound - at0) / along);
    }
  }
  return THREE.MathUtils.clamp(tMax, 0, 1);
}

function buildShaft(w: WindowDef, area: AreaDef, index: number, intensity: number): Shaft {
  const centre = new THREE.Vector3(...(w.centre as [number, number, number]));
  const right = new THREE.Vector3(...(w.right as [number, number, number])).multiplyScalar(w.width / 2);
  const up = new THREE.Vector3(0, w.height / 2, 0);
  const win = [
    centre.clone().sub(right).sub(up),
    centre.clone().add(right).sub(up),
    centre.clone().add(right).add(up),
    centre.clone().sub(right).add(up),
  ];
  // Parallel rays: projecting along the sun direction maps the window onto a parallelogram.
  const floor = win.map((p) => p.clone().addScaledVector(SUN_DIRECTION, -(p.y - FLOOR_Y) / SUN_DIRECTION.y));

  // Floor patch, clipped so it never spills outside the building.
  const corners: PoolPoint[] = floor.map((p, i) => ({ x: p.x, z: p.z, u: i === 1 || i === 2 ? 1 : 0, v: i >= 2 ? 1 : 0 }));
  const clipped = clipToArea(corners, area);
  let pool: THREE.BufferGeometry | null = null;
  if (clipped.length >= 3) {
    pool = new THREE.BufferGeometry();
    pool.setAttribute("position", new THREE.Float32BufferAttribute(clipped.flatMap((p) => [p.x, FLOOR_Y, p.z]), 3));
    pool.setAttribute("uv", new THREE.Float32BufferAttribute(clipped.flatMap((p) => [p.u, p.v]), 2));
    const idx: number[] = [];
    for (let i = 1; i < clipped.length - 1; i++) idx.push(0, i, i + 1);
    pool.setIndex(idx);
  }

  // Beam: each corner ray stops where it would hit the wall of this worship area.
  const ends = win.map((p, i) => p.clone().lerp(floor[i], exitParam(p, floor[i], area)));
  const pos: number[] = [];
  const t: number[] = [];
  const idx: number[] = [];
  for (let i = 0; i < 4; i++) {
    const j = (i + 1) % 4;
    const base = pos.length / 3;
    pos.push(...win[i].toArray(), ...win[j].toArray(), ...ends[j].toArray(), ...ends[i].toArray());
    t.push(0, 0, 1, 1);
    idx.push(base, base + 1, base + 2, base, base + 2, base + 3);
  }
  const beam = new THREE.BufferGeometry();
  beam.setAttribute("position", new THREE.Float32BufferAttribute(pos, 3));
  beam.setAttribute("aT", new THREE.Float32BufferAttribute(t, 1));
  beam.setIndex(idx);

  // Beam tint: the window's mean colour, pulled towards its dominant colour.
  const mean = new THREE.Color(0, 0, 0);
  let dominant = "amber";
  let best = -1;
  for (const [name, weight] of Object.entries(w.colours)) {
    const c = new THREE.Color(PALETTE[name]);
    mean.r += c.r * weight;
    mean.g += c.g * weight;
    mean.b += c.b * weight;
    if (weight > best) {
      best = weight;
      dominant = name;
    }
  }
  const beamColor = mean.lerp(new THREE.Color(PALETTE[dominant]), 0.4);

  const mid = win
    .map((p, i) => p.clone().add(ends[i]).multiplyScalar(0.5))
    .reduce((a, b) => a.add(b), new THREE.Vector3())
    .multiplyScalar(0.25);

  return {
    key: index,
    intensity,
    pool,
    beam,
    texture: makeMosaic(w.colours, 1000 + index),
    beamColor,
    mid: mid.toArray() as [number, number, number],
  };
}

const BEAM_VERTEX = /* glsl */ `
  attribute float aT;
  varying float vT;
  void main() {
    vT = aT;
    gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
  }
`;
const BEAM_FRAGMENT = /* glsl */ `
  uniform vec3 uColor;
  uniform float uOpacity;
  varying float vT;
  void main() {
    float fade = sin(3.14159265 * vT);
    gl_FragColor = vec4(uColor, uOpacity * fade * fade);
  }
`;

function Beam({ shaft }: { shaft: Shaft }) {
  const uniforms = useMemo(
    () => ({ uColor: { value: shaft.beamColor }, uOpacity: { value: 0.16 * shaft.intensity } }),
    [shaft],
  );
  return (
    <mesh geometry={shaft.beam} frustumCulled={false} renderOrder={2}>
      <shaderMaterial
        uniforms={uniforms}
        vertexShader={BEAM_VERTEX}
        fragmentShader={BEAM_FRAGMENT}
        transparent
        depthWrite={false}
        blending={THREE.AdditiveBlending}
        side={THREE.DoubleSide}
      />
    </mesh>
  );
}

export function WindowLight() {
  const roofOn = useChurchStore((s) => s.roof);

  const shafts = useMemo(() => {
    const areas = windowData.areas as AreaDef[];
    const out: Shaft[] = [];
    (windowData.windows as WindowDef[]).forEach((w, i) => {
      const facing = (w.outward[0] * SUN_DIRECTION.x + w.outward[2] * SUN_DIRECTION.z) / HORIZONTAL_SUN;
      if (facing > MIN_SUN) out.push(buildShaft(w, areas[w.area], i, Math.min(1, facing)));
    });
    return out;
  }, []);

  useEffect(
    () => () => {
      for (const s of shafts) {
        s.pool?.dispose();
        s.beam.dispose();
        s.texture.dispose();
      }
    },
    [shafts],
  );

  // With the roof off the interior is open to the sky, so the shafts would just float.
  if (!roofOn) return null;

  return (
    <group name="WindowLight">
      {shafts.map((s) => (
        <group key={s.key}>
          {s.pool && (
            <mesh geometry={s.pool} frustumCulled={false} renderOrder={1}>
              <meshBasicMaterial
                map={s.texture}
                transparent
                opacity={0.85 * s.intensity}
                depthWrite={false}
                blending={THREE.AdditiveBlending}
                side={THREE.DoubleSide}
                polygonOffset
                polygonOffsetFactor={-2}
              />
            </mesh>
          )}
          <Beam shaft={s} />
          <Sparkles
            count={10}
            size={2.5}
            scale={[2.4, 2.4, 2.4]}
            position={s.mid}
            speed={0.2}
            opacity={0.55}
            color="#ffe9c0"
            noise={0.4}
          />
        </group>
      ))}
    </group>
  );
}
